"""Methodology-aware cache fingerprinting, cache paths, load/save.

Ported verbatim from `legacy/Stat_Arb_cont_res_1.ipynb` (Sections 6, 19).

The notebook used two different cache-miss conventions inconsistently: the walk-forward
stability cache (`pair_stability_*.pkl`) hard-asserts on a miss (no in-notebook recompute,
since the screen is too expensive to run on a hot path -- see `scripts/run_stability_screen.py`),
while the Engle-Granger and WF1-selection caches silently compute-and-write on a miss. Both
conventions are preserved exactly as they were (this is a structural port, not a behavior
change) but are now named explicitly -- `load_or_assert` vs. `load_or_compute` -- so a caller
chooses the convention deliberately instead of it being an implicit per-cell difference.
"""
import hashlib
import os
import pickle
from typing import Callable

import pandas as pd

from config.research_config import DATA_CACHE_DIR


def cache_path(prefix: str, fingerprint: str) -> str:
    """Build a cache file's full path from its prefix and fingerprint, e.g.
    `cache_path('pair_stability', '523179f2a1')` -> `data/cache/pair_stability_523179f2a1.pkl`.
    Centralizes the cache location (`data/cache/`, `config.research_config.DATA_CACHE_DIR`) so
    callers never hand-build a relative `'../data/cache/...'` path themselves."""
    os.makedirs(DATA_CACHE_DIR, exist_ok=True)
    return os.path.join(DATA_CACHE_DIR, f'{prefix}_{fingerprint}.pkl')


def eg_cache_fingerprint(universe_cols, formation_start: str, formation_end: str) -> str:
    """S0's Section 6 Engle-Granger cache key: universe + formation window. A change to
    either invalidates the cache automatically rather than silently reusing results computed
    on a different universe or date range."""
    src = ','.join(sorted(universe_cols)) + '|' + formation_start + '|' + formation_end
    return hashlib.md5(src.encode()).hexdigest()[:10]


def wf_cache_fingerprint(*, universe_cols, rebalance_dates, wf_config: dict, extra: str = '') -> str:
    """Full methodology-aware cache fingerprint (feedback #3): hashes the universe, the
    rebalance-date schedule, AND every WF_CONFIG parameter that affects a walk-forward
    screen's result (coverage rule, EG alpha, FDR method, half-life/crossing/beta filters).
    Changing any one of these automatically produces a different fingerprint, so a stale
    cache can never be silently reused under a new methodology -- it simply won't be found.
    """
    methodology_src = '|'.join([
        f"min_obs={wf_config['MIN_OBS_FOR_TEST']}",
        f"coverage_frac={wf_config['MIN_COVERAGE_FRACTION']}",
        f"formation_months={wf_config['FORMATION_MONTHS']}",
        f"eg_alpha={wf_config['EG_ALPHA']}",
        f"fdr_method={wf_config['FDR_METHOD']}",
        f"max_hl={wf_config['MAX_HALF_LIFE_BARS']}",
        f"min_crossings={wf_config['MIN_CROSSINGS']}",
        f"positive_beta={wf_config['REQUIRE_POSITIVE_BETA']}",
        f"manual_exclude={sorted(wf_config['MANUAL_EXCLUDE'])}",
        f"extra={extra}",
    ])
    fingerprint_src = (','.join(sorted(universe_cols)) + '|' +
                        '|'.join(str(d.date()) for d in rebalance_dates) + '|' + methodology_src)
    return hashlib.md5(fingerprint_src.encode()).hexdigest()[:10]


def load_or_assert(path: str, error_msg: str) -> pd.DataFrame:
    """Load a pickle cache that must already exist -- used for expensive precomputes (the
    pair-stability screen) that are generated by a standalone script, never on a notebook's
    hot path. Raises a loud, actionable AssertionError if missing."""
    assert os.path.exists(path), error_msg
    return pd.read_pickle(path)


def load_or_compute(path: str, compute_fn: Callable[[], object]):
    """Load a pickle cache if present, otherwise compute it via `compute_fn()` and write it."""
    if os.path.exists(path):
        with open(path, 'rb') as f:
            return pickle.load(f)
    result = compute_fn()
    with open(path, 'wb') as f:
        pickle.dump(result, f)
    return result
